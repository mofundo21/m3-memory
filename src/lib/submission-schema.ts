import { z } from "zod";

const optionalText = (max = 10000) => z.string().trim().max(max).optional().default("");
const socialProfileSchema = z.object({
  platform: z.enum(["Instagram", "TikTok", "Facebook", "X / Twitter", "Threads", "YouTube", "Snapchat", "Discord", "Twitch", "LinkedIn", "Chess.com", "Website", "Other"]),
  handle: z.string().trim().min(1).max(300),
  howWeMet: z.boolean().default(false),
});

export const submissionSchema = z.object({
  displayName: z.string().trim().min(1).max(120),
  email: z.string().trim().email().max(320),
  instagram: z.string().trim().max(200).optional().default(""),
  socialProfiles: z.array(socialProfileSchema).max(12).optional().default([]),
  knownAsAtTime: optionalText(200),
  livingAtTime: optionalText(300),
  relationshipToday: optionalText(100),
  relationshipTodayOther: optionalText(300),
  dateCertainty: z.enum(["exact", "approximate", "unknown"]),
  occurredOn: z.string().optional().default(""),
  approximateDateText: z.string().trim().max(200).optional().default(""),
  eventName: z.string().trim().max(200).optional().default(""),
  venue: z.string().trim().max(200).optional().default(""),
  city: z.string().trim().max(120).optional().default(""),
  region: z.string().trim().max(120).optional().default(""),
  country: z.string().trim().max(120).optional().default(""),
  definitelyFirstMeeting: optionalText(40),
  timeOfDay: optionalText(40),
  exactPlace: optionalText(1000),
  contributorWith: optionalText(1000),
  mofundoWith: optionalText(1000),
  introducedBy: optionalText(500),
  surroundings: optionalText(),
  immediatelyBefore: optionalText(),
  timeTogether: optionalText(60),
  story: z.string().trim().min(20).max(20000),
  conversationDetails: z.string().trim().max(10000).optional().default(""),
  mofundoWearing: z.string().trim().max(4000).optional().default(""),
  contributorWearing: z.string().trim().max(4000).optional().default(""),
  mofundoHairStyle: optionalText(4000),
  mofundoCarrying: optionalText(4000),
  contributorCarrying: optionalText(4000),
  musicPlaying: optionalText(4000),
  artistOrSet: optionalText(4000),
  placeAppearance: optionalText(),
  distinctiveNearby: optionalText(),
  rememberedHearing: optionalText(),
  rememberedSeeing: optionalText(),
  firstImpression: z.string().trim().max(10000).optional().default(""),
  impressionBeforeTalking: optionalText(),
  impressionAfterTalking: optionalText(),
  mofundoExactWords: optionalText(),
  contributorExactWords: optionalText(),
  mofundoWorkDiscussed: optionalText(),
  talkedAboutMusic: optionalText(40),
  talkedAboutPersonal: optionalText(40),
  storyTold: optionalText(),
  rememberedQuoteOrJoke: optionalText(),
  meaningfulDetails: z.string().trim().max(10000).optional().default(""),
  thingsExchanged: z.string().trim().max(10000).optional().default(""),
  keptHangingOut: optionalText(40),
  exchangedContact: optionalText(40),
  contactedAfterward: optionalText(40),
  toldAnyone: optionalText(40),
  toldAnyoneDetails: optionalText(),
  expectedToMeetAgain: optionalText(40),
  seenSince: optionalText(40),
  nextSeenWhere: optionalText(1000),
  nextSeenWhen: optionalText(500),
  nextEncounterStory: optionalText(),
  meetingCount: optionalText(40),
  connectionToday: optionalText(),
  lifeEffect: optionalText(),
  watchedChange: optionalText(40),
  changeObserved: optionalText(),
  firstKnownIdentity: optionalText(40),
  knewMusicAtTime: optionalText(40),
  knewBookAtTime: optionalText(40),
  forgottenDetail: z.string().trim().max(10000).optional().default(""),
  bookPageMessage: z.string().trim().max(10000).optional().default(""),
  smallestDetail: optionalText(),
  neverToldDetail: optionalText(),
  differingMemory: optionalText(),
  archiveStorage: z.literal(true),
  truthful: z.literal(true),
  mediaRights: z.literal(true),
  publicWebsite: z.boolean().default(false),
  bookEditorial: z.boolean().default(false),
  displayPublicName: z.boolean().default(false),
  displaySocial: z.boolean().default(false),
  followUpContact: z.boolean().default(false),
}).superRefine((value, context) => {
  if (value.dateCertainty === "exact" && !value.occurredOn) context.addIssue({ code: "custom", path: ["occurredOn"], message: "Choose the exact date." });
  if (value.dateCertainty === "approximate" && !value.approximateDateText) context.addIssue({ code: "custom", path: ["approximateDateText"], message: "Describe the approximate date." });
});

export type SubmissionInput = z.infer<typeof submissionSchema>;
